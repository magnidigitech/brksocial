// Helper: Get Parliament details by Code
export function getParliamentByCode(code) {
  return AP_CONSTITUENCIES.find(p => p.code === code) || null;
}

// Helper: Get Assembly details by Code
export function getAssemblyByCode(asmCode) {
  for (const p of AP_CONSTITUENCIES) {
    const asm = p.assemblies.find(a => a.code === asmCode);
    if (asm) {
      return {
        ...asm,
        parliamentCode: p.code,
        parliamentName: p.name
      };
    }
  }
  return null;
}
